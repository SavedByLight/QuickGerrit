    val n = it.name
    n.contains("compileKotlinDesktop", ignoreCase = true) ||
        n.contains("compileDesktopMain", ignoreCase = true) ||
        n.startsWith("desktop") && n.contains("Kotlin", ignoreCase = true)
}.configureEach {
    dependsOn(generateDesktopVersion)
}

