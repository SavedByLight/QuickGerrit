// ---- Version / GitHub repo (CI passes -PversionName -PversionCode -PgithubRepo) ----
fun String.cleanVersion(): String =
    removePrefix("v").substringBefore("-").trim().ifBlank { "1.0.0" }

val versionNameProp: String =
    (findProperty("versionName") as String?)?.cleanVersion()
        ?: (findProperty("VERSION_NAME") as String?)?.cleanVersion()
        ?: "1.0.0"

val versionCodeProp: Int =
    (findProperty("versionCode") as String?)?.toIntOrNull()
        ?: versionNameProp.substringAfterLast('.').filter { it.isDigit() }.toIntOrNull()
        ?: 1

val githubRepoProp: String =
    (findProperty("githubRepo") as String?)
        ?: System.getenv("GITHUB_REPOSITORY")
        ?: (findProperty("GITHUB_REPO") as String?)
        ?: ""

val generateDesktopVersion by tasks.registering {
    val outFile = layout.projectDirectory
        .file("src/desktopMain/kotlin/com/quickgerrit/app/platform/GeneratedVersion.kt")
        .asFile
    inputs.property("versionName", versionNameProp)
    inputs.property("versionCode", versionCodeProp)
    inputs.property("githubRepo", githubRepoProp)
    outputs.file(outFile)
    doLast {
        outFile.parentFile.mkdirs()
        // Escape for Kotlin string
        val repoEscaped = githubRepoProp.replace("\\", "\\\\").replace("\"", "\\\"")
        outFile.writeText(
            """
            package com.quickgerrit.app.platform

            /** AUTO-GENERATED by Gradle generateDesktopVersion — do not edit. */
            object GeneratedVersion {
                const val VERSION_NAME: String = "$versionNameProp"
                const val VERSION_CODE: Int = $versionCodeProp
                const val GITHUB_REPO: String = "$repoEscaped"
            }
            """.trimIndent() + "\n"
        )
        logger.lifecycle(
            "GeneratedVersion → VERSION_NAME=$versionNameProp VERSION_CODE=$versionCodeProp GITHUB_REPO=${githubRepoProp.ifBlank { "(empty)" }}"
        )
    }
}

// Ensure every desktop compile regenerates version constants
